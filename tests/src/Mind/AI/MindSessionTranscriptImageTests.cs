using AlleyCat.Mind.AI;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.Logging;
using Xunit;

namespace AlleyCat.Tests.Mind.AI;

/// <summary>
/// Tests the AI-011 transcript-image contracts added by AI-013 (TR-26–TR-28): sibling PNG/JPEG files beside the
/// generating turn page with turn-derived unique names, exactly-once writes, relative links at the carrying
/// invocation position with a per-cycle listing, no image files for placeholder-only or image-free cycles, an
/// unchanged index, and contained image-write failures that never remove the turn page.
/// </summary>
[Collection(MindSessionTranscriptSeamCollection.Name)]
public sealed class MindSessionTranscriptImageTests : IDisposable
{
    private readonly string _rootDirectory = Path.Combine(
        Path.GetTempPath(),
        "AlleyCat.MindSessionTranscriptImageTests",
        Guid.NewGuid().ToString("N"));

    private readonly RecordingLogger _logger = new();

    /// <summary>Resets the process-wide turn counters and redirects the recorder root to a fresh temporary tree.</summary>
    public MindSessionTranscriptImageTests()
    {
        MindSessionTranscriptRecorder.ResetTurnCountersForTesting();
        MindSessionTranscriptRecorder.SetRootPathOverrideForTesting(_rootDirectory);
    }

    /// <summary>Restores the recorder seams and deletes the temporary transcript tree.</summary>
    public void Dispose()
    {
        MindSessionTranscriptRecorder.SetRootPathOverrideForTesting(null);
        MindSessionTranscriptRecorder.ResetTurnCountersForTesting();
        try
        {
            Directory.Delete(_rootDirectory, recursive: true);
        }
        catch (DirectoryNotFoundException)
        {
            // Nothing was written; the root never existed.
        }
    }

    /// <summary>
    /// A cycle generating a minimap and a view capture writes each image exactly once as a sibling file beside its
    /// turn page — minimap PNG, view JPEG — with the generated bytes, and the turn page embeds relative links at
    /// the carrying invocation blocks and lists both images per cycle (AI-011 TR-26–TR-27).
    /// </summary>
    [Fact]
    public void Record_WithImageGeneratingCycle_WritesSiblingFilesAndLinksThemOnTheTurnPage()
    {
        byte[] minimapBytes = [1, 2, 3];
        byte[] viewBytes = [4, 5];
        MindSessionCycleTranscript cycle = CreateCycle(
            CreateInvocation("look_around", CompletedResult(), VisualContextImage.Minimap(
                minimapBytes,
                centreX: 1.5,
                centreY: 2.5,
                radiusMetres: 10,
                gameTimeSeconds: 42.5)),
            CreateInvocation("capture_view", CompletedResult(), VisualContextImage.View(viewBytes, gameTimeSeconds: 42.5)));

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = GetCharacterDirectory();
        Assert.Equal(
            ["turn-0001-minimap-1.png", "turn-0001-view-1.jpg"],
            Directory.GetFiles(characterDirectory)
                .Select(Path.GetFileName)
                .Where(static name => name is { } fileName && !fileName.EndsWith(".md", StringComparison.Ordinal))
                .OrderBy(static name => name));
        Assert.Equal(minimapBytes, File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-1.png")));
        Assert.Equal(viewBytes, File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-view-1.jpg")));

        string turnPage = File.ReadAllText(Path.Combine(characterDirectory, "turn-0001.md"));
        Assert.Contains("![minimap](turn-0001-minimap-1.png)", turnPage, StringComparison.Ordinal);
        Assert.Contains("![view](turn-0001-view-1.jpg)", turnPage, StringComparison.Ordinal);
        Assert.Contains(
            "minimap image centred at (1.5, 2.5) covering a 10 m radius, captured at game time 42.5 s",
            turnPage,
            StringComparison.Ordinal);
        Assert.Contains("## Generated Images", turnPage, StringComparison.Ordinal);
        Assert.Contains(
            "- **minimap:** [turn-0001-minimap-1.png](turn-0001-minimap-1.png) —",
            turnPage,
            StringComparison.Ordinal);
        Assert.Contains(
            "- **view:** [turn-0001-view-1.jpg](turn-0001-view-1.jpg) —",
            turnPage,
            StringComparison.Ordinal);

        // The invocation index stays unchanged by this amendment and carries no image links (AI-011 TR-27).
        string index = File.ReadAllText(Path.Combine(characterDirectory, "index.md"));
        Assert.DoesNotContain("](turn-0001-minimap-1.png)", index, StringComparison.Ordinal);
        Assert.DoesNotContain("](turn-0001-view-1.jpg)", index, StringComparison.Ordinal);
        Assert.Contains("look_around", index, StringComparison.Ordinal);
    }

    /// <summary>
    /// Two images of the same kind in one cycle receive distinct per-kind ordinals, keeping file names unique
    /// within the character folder (AI-011 TR-26).
    /// </summary>
    [Fact]
    public void Record_WithTwoImagesOfOneKind_NumbersThemUniquely()
    {
        MindSessionCycleTranscript cycle = CreateCycle(
            CreateInvocation("look_around", CompletedResult(), VisualContextImage.Minimap([1])),
            CreateInvocation("look_around", CompletedResult(), VisualContextImage.Minimap([2])));

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = GetCharacterDirectory();
        Assert.Equal(
            ["turn-0001-minimap-1.png", "turn-0001-minimap-2.png"],
            Directory.GetFiles(characterDirectory, "turn-*.png").Select(Path.GetFileName).Order());
        Assert.Equal([1], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-1.png")));
        Assert.Equal([2], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-2.png")));
    }

    /// <summary>
    /// A cycle that generated no image — including one whose request transcript replays a live image presentation
    /// from an earlier cycle — writes no image file: the replay renders as a textual image-content reference
    /// without a link, and a disposed placeholder renders as text (AI-011 TR-27).
    /// </summary>
    [Fact]
    public void Record_WithoutGeneratedImages_WritesNoImageFileAndRendersReplaysWithoutLinks()
    {
        var replayed = VisualContextImage.View([9, 9], gameTimeSeconds: 5);
        ChatMessage presentation = new(
            ChatRole.User,
            [
                new TextContent("Visual context from your tool action: view capture through your own eyes, captured "
                    + "at game time 5 s."),
                replayed,
            ]);
        ChatMessage disposed = new(
            ChatRole.User,
            [new TextContent(replayed.ToDisposalPlaceholder())]);
        MindSessionCycleTranscript cycle = CreateCycle(
            requestMessages:
            [
                new ChatMessage(ChatRole.User, "Begin."),
                presentation,
                disposed,
            ]);

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = GetCharacterDirectory();
        Assert.Equal(["index.md", "turn-0001.md"], Directory.GetFiles(characterDirectory).Select(Path.GetFileName).Order());
        string turnPage = File.ReadAllText(Path.Combine(characterDirectory, "turn-0001.md"));
        Assert.Contains(
            "_(image content — view capture through your own eyes, captured at game time 5 s",
            turnPage,
            StringComparison.Ordinal);
        Assert.DoesNotContain("](turn-", turnPage, StringComparison.Ordinal);
        Assert.DoesNotContain("## Generated Images", turnPage, StringComparison.Ordinal);
        Assert.Contains("[Image no longer available", turnPage, StringComparison.Ordinal);
    }

    /// <summary>
    /// A failing image write is contained exactly like any recording failure (AI-011 TR-28): it warns without
    /// disturbing the session, the already-written turn page stays intact, later images of the same cycle still
    /// write, and the index still updates.
    /// </summary>
    [Fact]
    public void Record_WhenAnImageWriteFails_WarnsAndKeepsTheTurnPageAndOtherImages()
    {
        // A throwaway record for another character latches the process run directory under this test's root, so the
        // blocking directory can be created at the failing image's exact target path beforehand.
        CreateRecorder("moss").Record(CreateCycle());
        string runDirectory = Assert.Single(Directory.GetDirectories(_rootDirectory));
        MindSessionCycleTranscript cycle = CreateCycle(
            CreateInvocation("look_around", CompletedResult(), VisualContextImage.Minimap([1])),
            CreateInvocation("capture_view", CompletedResult(), VisualContextImage.View([2])));

        // Blocking the first image's target path with a directory forces its write to fail.
        _ = Directory.CreateDirectory(Path.Combine(runDirectory, "luna", "turn-0001-minimap-1.png"));

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = Path.Combine(runDirectory, "luna");
        Assert.True(File.Exists(Path.Combine(characterDirectory, "turn-0001.md")));
        Assert.Equal([2], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-view-1.jpg")));
        Assert.True(File.Exists(Path.Combine(characterDirectory, "index.md")));
        Assert.Contains(_logger.Entries, entry =>
            entry.Level == LogLevel.Warning
            && entry.Message.Contains("Failed to write a mind session transcript image", StringComparison.Ordinal));
    }

    /// <summary>
    /// A cycle whose fresh request-suffix message carried generated images — the auto-mode visual-context message
    /// — writes each exactly once as a sibling file beside its turn page, embeds the relative links at the
    /// carrying message's position in the request transcript, and lists them per cycle (AI-011 TR-26–TR-27;
    /// AI-013 TR-8).
    /// </summary>
    [Fact]
    public void Record_WithMessageCarriedImages_WritesSiblingFilesAndLinksThemAtTheMessagePosition()
    {
        var minimap = VisualContextImage.Minimap([7, 7, 7], centreX: 1, centreY: -2, radiusMetres: 100, gameTimeSeconds: 12);
        var view = VisualContextImage.View([8, 8], gameTimeSeconds: 12);
        ChatMessage visualContext = new(
            ChatRole.User,
            [new TextContent("Current visual context:"), minimap, view]);
        MindSessionCycleTranscript cycle = CreateCycle(
            requestMessages:
            [
                new ChatMessage(ChatRole.User, "Begin."),
                visualContext,
                new ChatMessage(ChatRole.User, "Fresh scene status."),
            ]);
        cycle.MessageImages.Add(new MindTranscriptMessageImage(1, minimap));
        cycle.MessageImages.Add(new MindTranscriptMessageImage(1, view));

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = GetCharacterDirectory();
        Assert.Equal(
            ["turn-0001-minimap-1.png", "turn-0001-view-1.jpg"],
            Directory.GetFiles(characterDirectory)
                .Select(Path.GetFileName)
                .Where(static name => name is { } fileName && !fileName.EndsWith(".md", StringComparison.Ordinal))
                .OrderBy(static name => name));
        Assert.Equal([7, 7, 7], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-1.png")));
        Assert.Equal([8, 8], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-view-1.jpg")));

        string turnPage = File.ReadAllText(Path.Combine(characterDirectory, "turn-0001.md"));
        Assert.Contains("![minimap](turn-0001-minimap-1.png)", turnPage, StringComparison.Ordinal);
        Assert.Contains("![view](turn-0001-view-1.jpg)", turnPage, StringComparison.Ordinal);
        Assert.Contains(
            "- **minimap:** [turn-0001-minimap-1.png](turn-0001-minimap-1.png) —",
            turnPage,
            StringComparison.Ordinal);
        Assert.Contains(
            "- **view:** [turn-0001-view-1.jpg](turn-0001-view-1.jpg) —",
            turnPage,
            StringComparison.Ordinal);

        // The invocation index stays unchanged by the amendment and carries no image links (AI-011 TR-27).
        string index = File.ReadAllText(Path.Combine(characterDirectory, "index.md"));
        Assert.DoesNotContain("](turn-0001-minimap-1.png)", index, StringComparison.Ordinal);
        Assert.DoesNotContain("](turn-0001-view-1.jpg)", index, StringComparison.Ordinal);
    }

    /// <summary>
    /// Message-carried images of one cycle number per kind across both carriers, keeping file names unique within
    /// the character folder (AI-011 TR-26).
    /// </summary>
    [Fact]
    public void Record_WithInvocationAndMessageImagesOfOneKind_NumbersThemUniquely()
    {
        var toolImage = VisualContextImage.Minimap([1]);
        var messageImage = VisualContextImage.Minimap([2]);
        MindSessionCycleTranscript cycle = CreateCycle(
            requestMessages:
            [
                new ChatMessage(ChatRole.User, "Begin."),
                new ChatMessage(ChatRole.User, [new TextContent("Current visual context:"), messageImage]),
            ]);
        cycle.ToolInvocations.Add(
            new MindTranscriptToolInvocation("look_around", "call-1", new Dictionary<string, object?>())
            {
                Status = MindTranscriptToolInvocationStatus.Completed,
                Result = "Delivered.",
                GeneratedImage = toolImage,
            });
        cycle.MessageImages.Add(new MindTranscriptMessageImage(1, messageImage));

        CreateRecorder("luna").Record(cycle);

        string characterDirectory = GetCharacterDirectory();
        Assert.Equal(
            ["turn-0001-minimap-1.png", "turn-0001-minimap-2.png"],
            Directory.GetFiles(characterDirectory, "turn-*.png").Select(Path.GetFileName).Order());
        Assert.Equal([1], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-1.png")));
        Assert.Equal([2], File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-2.png")));
    }

    private static object? CompletedResult() => "Delivered.";

    private string GetCharacterDirectory()
    {
        string runDirectory = Assert.Single(Directory.GetDirectories(_rootDirectory));
        return Assert.Single(Directory.GetDirectories(runDirectory, "luna"));
    }

    private MindSessionTranscriptRecorder CreateRecorder(string characterId)
        => new(characterId, () => _rootDirectory, _logger);

    private static MindSessionCycleTranscript CreateCycle(
        params MindTranscriptToolInvocation[] invocations)
        => CreateCycle(requestMessages: [new ChatMessage(ChatRole.User, "Begin.")], invocations);

    private static MindSessionCycleTranscript CreateCycle(
        IReadOnlyList<ChatMessage> requestMessages,
        params MindTranscriptToolInvocation[] invocations)
    {
        MindSessionCycleTranscript cycle = new()
        {
            CycleIndex = 1,
            StartedAt = DateTimeOffset.Now,
            Instructions = "<Identity>\nYou are Luna.\n</Identity>\n",
            RequestMessages = requestMessages,
            RequestOptions = new MindTranscriptRequestOptions(null, "RequiredChatToolMode", ["look_around"]),
        };
        cycle.ToolInvocations.AddRange(invocations);
        return cycle;
    }

    private static MindTranscriptToolInvocation CreateInvocation(
        string toolName,
        object? result,
        VisualContextImage image)
        => new(toolName, "call-1", new Dictionary<string, object?>())
        {
            Status = MindTranscriptToolInvocationStatus.Completed,
            Result = result,
            GeneratedImage = image,
        };

    private sealed class RecordingLogger : ILogger
    {
        public List<(LogLevel Level, string Message)> Entries { get; } = [];

        public IDisposable? BeginScope<TState>(TState state) where TState : notnull => null;

        public bool IsEnabled(LogLevel logLevel) => true;

        public void Log<TState>(
            LogLevel logLevel,
            EventId eventId,
            TState state,
            Exception? exception,
            Func<TState, Exception?, string> formatter)
            => Entries.Add((logLevel, formatter(state, exception)));
    }
}
