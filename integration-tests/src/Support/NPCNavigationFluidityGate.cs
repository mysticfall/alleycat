/// <summary>Deterministic, printable evaluation result for one recorded NPC bout.</summary>
public sealed record NPCFluidityGateResult(
    string CaseName,
    bool Passed,
    IReadOnlyList<NPCFluidityViolation> Violations,
    NPCFluidityCaseStatistics Statistics,
    IReadOnlyList<FluidityContactRejection> RejectedSamples)
{
    public string BuildReport()
    {
        StringBuilder builder = new();
        _ = builder.AppendLine($"NPC fluidity gate report: {CaseName}");
        _ = builder.AppendLine(
            $"Tick: {Fmt(Statistics.TickSeconds)} s ({1f / Statistics.TickSeconds:0.##} Hz)  Samples: {Statistics.SampleCount}  Duration: {Fmt(Statistics.DurationSeconds)} s  Excluded: {Statistics.ExcludedSampleCount}");
        _ = builder.AppendLine(
            Statistics.TravelStartSeconds is float travelStart
                ? $"Travel start: {Fmt(travelStart)} s"
                : "Travel start: <never observed>");
        AppendFootStatistics(builder, "left", Statistics.LeftFoot);
        AppendFootStatistics(builder, "right", Statistics.RightFoot);
        _ = builder.AppendLine(Passed ? "Result: PASS" : $"Result: FAIL ({Violations.Count} violations)");
        foreach (NPCFluidityViolation violation in Violations.OrderBy(v => v.TimeSeconds).ThenBy(v => v.Metric).ThenBy(v => v.Foot))
        {
            _ = builder.AppendLine(
                $"  {violation.Metric}({violation.Foot}): {Fmt(violation.Value)} > {Fmt(violation.Threshold)} @ {Fmt(violation.TimeSeconds)} s [{violation.Context}]");
        }

        foreach (FluidityContactRejection rejection in RejectedSamples.OrderBy(rejection => rejection.SampleIndex).ThenBy(rejection => rejection.Foot))
        {
            _ = builder.AppendLine($"  rejected contact sample {rejection.SampleIndex} ({rejection.Foot}) @ {Fmt(rejection.TimeSeconds)} s: {rejection.Reason}");
        }

        string exceedances = Statistics.SpecView.BuildExceedances();
        if (exceedances.Length > 0)
        {
            _ = builder.AppendLine("Historical NAV-001 reference-limit diagnostic view:");
            _ = builder.Append(exceedances);
        }

        return builder.ToString();
    }

    private static void AppendFootStatistics(StringBuilder builder, string foot, NPCFluidityFootStatistics statistics)
    {
        _ = builder.AppendLine(
            $"{foot}: stance intervals {statistics.StanceIntervalCount}, max slip speed {Fmt(statistics.MaximumStanceSlipSpeed)} m/s @ {Fmt(statistics.MaximumStanceSlipSpeedTimeSeconds)} s, max slip distance {Fmt(statistics.MaximumStanceSlipDistance)} m, max swing speed {Fmt(statistics.MaximumSwingPlanarSpeed)} m/s @ {Fmt(statistics.MaximumSwingPlanarSpeedTimeSeconds)} s, max speed discontinuity {Fmt(statistics.MaximumSpeedDiscontinuity)} m/s^2 @ {Fmt(statistics.MaximumSpeedDiscontinuityTimeSeconds)} s");
        _ = builder.AppendLine($"{foot}: swing onset times (s): {FormatList(statistics.SwingOnsetTimesSeconds)}");
        _ = builder.AppendLine($"{foot}: travel step intervals (s): {FormatList(statistics.TravelStepIntervalsSeconds)}");
    }

    private static string FormatList(IReadOnlyList<float> values)
        => values.Count == 0 ? "<none>" : string.Join(", ", values.Select(Fmt));

    private static string Fmt(float value) => value.ToString("0.000", CultureInfo.InvariantCulture);
}

/// <summary>
/// Pure analysis library for the NAV-001 NPC navigation fluidity gate. It consumes supplied authoritative contact
/// evidence rather than inferring support from foot height; missing or rejected evidence fails closed. Historical
/// NAV-001 reference limits are reported separately from the binding calibrated measurements.
/// </summary>
public static class NPCNavigationFluidityGate
{
    private const string TravelNodeName = "NPCTravel";

    public static NPCFluidityGateResult Evaluate(
        string caseName,
        IReadOnlyList<NPCFluiditySample> samples,
        IReadOnlyList<NPCFluidityNodeSegment> nodeTimeline,
        NPCFluidityGateThresholds thresholds,
        FluidityExpectedSupportPopulation? expectedSupport = null)
    {
        if (samples.Count < 3)
        {
            return Fail(caseName, samples, new NPCFluidityViolation(
                "SampleCount", "both", samples.Count, 3f, 0f, "insufficient samples for analysis"));
        }

        float tick = samples[1].TimeSeconds - samples[0].TimeSeconds;
        if (!float.IsFinite(tick) || tick <= 0f)
        {
            return Fail(caseName, samples, new NPCFluidityViolation(
                "SampleTick", "both", tick, 0.0001f, samples[1].TimeSeconds, "non-monotonic sample times"));
        }

        FluidityContactValidation contact = FluidityContactOracle.Validate(
            samples,
            static sample => sample.TimeSeconds,
            static sample => sample.Contacts,
            expectedSupport);

        bool[] excluded = BuildExclusionMask(samples, nodeTimeline, thresholds);
        SampleView view = BuildSampleView(samples, nodeTimeline);
        FootTracks left = BuildFootTracks(samples, view, static sample => sample.LeftFootWorld, static sample => sample.Contacts?.Left, tick, contact.LeftFullSupport);
        FootTracks right = BuildFootTracks(samples, view, static sample => sample.RightFootWorld, static sample => sample.Contacts?.Right, tick, contact.RightFullSupport);

        float? travelStart = nodeTimeline
            .Where(segment => segment.NodeName == TravelNodeName)
            .Select(segment => (float?)segment.EnterTimeSeconds)
            .FirstOrDefault();

        List<NPCFluidityViolation> violations = [];
        violations.AddRange(contact.Rejections.Select(rejection => new NPCFluidityViolation(
            "ContactEvidence",
            rejection.Foot,
            rejection.SampleIndex,
            0f,
            rejection.TimeSeconds,
            rejection.Reason)));
        NPCFluidityFootStatistics leftStatistics = EvaluateFootSlipAndSpeed("left", left, excluded, tick, thresholds, violations);
        NPCFluidityFootStatistics rightStatistics = EvaluateFootSlipAndSpeed("right", right, excluded, tick, thresholds, violations);
        (leftStatistics, rightStatistics) = EvaluatePhaseConsistency(
            ("left", left, leftStatistics), ("right", right, rightStatistics),
            excluded, thresholds, travelStart, violations);

        NPCFluiditySpecView specView = EvaluateSpecView(samples, tick, left, right, excluded);
        NPCFluidityCaseStatistics statistics = new(
            samples.Count,
            tick,
            samples[^1].TimeSeconds,
            travelStart,
            excluded.Count(static value => value),
            leftStatistics,
            rightStatistics,
            specView);
        return new NPCFluidityGateResult(caseName, violations.Count == 0, violations, statistics, contact.Rejections);
    }

    /// <summary>
    /// NAV-001 item 9 view: root planar speed discontinuity and acceleration from the virtual root (the
    /// authored root-motion plan), and support-foot slip per sample / per contact interval from supplied
    /// authoritative full-support evidence.
    /// </summary>
    private static NPCFluiditySpecView EvaluateSpecView(
        IReadOnlyList<NPCFluiditySample> samples,
        float tick,
        FootTracks left,
        FootTracks right,
        bool[] excluded)
    {
        float maxSpeedStep = 0f;
        float maxAcceleration = 0f;
        Vector2 previousSpeed = Vector2.Zero;
        for (int i = 1; i < samples.Count; i++)
        {
            if (excluded[i] || excluded[i - 1])
            {
                previousSpeed = Vector2.Zero;
                continue;
            }

            Vector2 delta = new(
                samples[i].RootWorld.X - samples[i - 1].RootWorld.X,
                samples[i].RootWorld.Z - samples[i - 1].RootWorld.Z);
            Vector2 speed = delta / tick;
            float step = speed.DistanceTo(previousSpeed);
            maxSpeedStep = Mathf.Max(maxSpeedStep, step);
            maxAcceleration = Mathf.Max(maxAcceleration, (speed.Length() - previousSpeed.Length()) / tick);
            previousSpeed = speed;
        }

        return new NPCFluiditySpecView(
            maxSpeedStep,
            maxAcceleration,
            Mathf.Max(MaxSlipPerSample(left), MaxSlipPerSample(right)),
            Mathf.Max(
                Mathf.Max(MaxSlipPerInterval(left), MaxSlipPerInterval(right)),
                Mathf.Max(MaxSlipPerSample(left), MaxSlipPerSample(right))));
    }

    private static float MaxSlipPerSample(FootTracks tracks)
    {
        float maximum = 0f;
        for (int i = 1; i < tracks.Stance.Length; i++)
        {
            if (tracks.Stance[i])
            {
                maximum = Mathf.Max(maximum, tracks.Planar[i].DistanceTo(tracks.Planar[i - 1]));
            }
        }

        return maximum;
    }

    private static float MaxSlipPerInterval(FootTracks tracks)
    {
        float maximum = 0f;
        int count = tracks.Stance.Length;
        int runStart = -1;
        for (int i = 0; i <= count; i++)
        {
            bool inStance = i < count && tracks.Stance[i];
            if (inStance && runStart < 0)
            {
                runStart = i;
            }
            else if (!inStance && runStart >= 0)
            {
                if (i - runStart > 0)
                {
                    maximum = Mathf.Max(maximum, tracks.Planar[i - 1].DistanceTo(tracks.Planar[runStart]));
                }

                runStart = -1;
            }
        }

        return maximum;
    }

    private static NPCFluidityGateResult Fail(
        string caseName,
        IReadOnlyList<NPCFluiditySample> samples,
        NPCFluidityViolation violation)
        => new(caseName, false, [violation], CreateEmptyStatistics(samples), []);

