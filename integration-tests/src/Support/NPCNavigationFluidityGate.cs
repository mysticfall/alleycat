/// <summary>
/// Historical NAV-001 reference-limit diagnostic view. Stage 0 deliberately defers final numeric correction caps
/// and role-specific slip/anchor thresholds until the both-rig prototype Gate B, so these values are reported only
/// and never influence gate acceptance.
/// </summary>
public sealed record NPCFluiditySpecView(
    float MaximumRootSpeedStepMetresPerSecond,
    float MaximumRootAccelerationMetresPerSecondSquared,
    float MaximumSupportFootSlipPerSampleMetres,
    float MaximumSupportFootSlipPerContactIntervalMetres)
{
    public static NPCFluiditySpecView Limits
    {
        get;
    } = new(0.20f, 8.0f, 0.005f, 0.015f);

    public string BuildExceedances()
    {
        StringBuilder builder = new();
        if (MaximumRootSpeedStepMetresPerSecond > Limits.MaximumRootSpeedStepMetresPerSecond)
        {
            _ = builder.AppendLine(
                $"  SPEC root speed step {MaximumRootSpeedStepMetresPerSecond:0.000} > {Limits.MaximumRootSpeedStepMetresPerSecond:0.000} m/s");
        }

        if (MaximumRootAccelerationMetresPerSecondSquared > Limits.MaximumRootAccelerationMetresPerSecondSquared)
        {
            _ = builder.AppendLine(
                $"  SPEC root acceleration {MaximumRootAccelerationMetresPerSecondSquared:0.0} > {Limits.MaximumRootAccelerationMetresPerSecondSquared:0.0} m/s^2");
        }

        if (MaximumSupportFootSlipPerSampleMetres > Limits.MaximumSupportFootSlipPerSampleMetres)
        {
            _ = builder.AppendLine(
                $"  SPEC support-foot slip/sample {MaximumSupportFootSlipPerSampleMetres * 1000:0.0} > {Limits.MaximumSupportFootSlipPerSampleMetres * 1000:0.0} mm");
        }

        if (MaximumSupportFootSlipPerContactIntervalMetres > Limits.MaximumSupportFootSlipPerContactIntervalMetres)
        {
            _ = builder.AppendLine(
                $"  SPEC support-foot slip/contact {MaximumSupportFootSlipPerContactIntervalMetres * 1000:0.0} > {Limits.MaximumSupportFootSlipPerContactIntervalMetres * 1000:0.0} mm");
        }

        return builder.ToString();
    }
}

