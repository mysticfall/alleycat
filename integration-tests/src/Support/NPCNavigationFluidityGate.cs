/// <summary>
/// Thresholds for the NPC navigation fluidity gate, recalibrated from measured NAV-001 evidence. Every default
/// cites its measurement; artefacts live under game/temp/nav001-fluidity-gate (regenerated by
/// NPCNavigationFluidityGateCalibrationTests).
/// </summary>
/// <param name="StanceContactOffsetMetres">Foot-bone height above the tracked ground below which the foot counts as planted.</param>
/// <param name="StanceMaximumVerticalSpeed">Vertical speed below which a low foot counts as planted.</param>
/// <param name="GroundTrackWindowSeconds">Rolling window over which the lower foot's minimum height is tracked as the ground level.</param>
/// <param name="MinimumStanceSamples">Shortest stance run (in ticks) that is measured; shorter runs merge into swing.</param>
/// <param name="MinimumSwingSamples">Shortest swing run (in ticks) that counts as a step onset.</param>
/// <param name="MaximumStanceSlipSpeed">Planar speed a planted foot may reach before the sample is a skating violation (m/s).</param>
/// <param name="MaximumStanceSlipDistance">Planar distance a planted foot may accumulate over one stance interval (m).</param>
/// <param name="MaximumSwingPlanarSpeed">Planar speed cap for any foot at any time (m/s).</param>
/// <param name="MaximumSpeedDiscontinuity">Frame-to-frame planar speed change cap per foot (m/s²).</param>
/// <param name="TravelPhaseWarmupSeconds">Grace after entering NPCTravel before step-phase metrics are enforced.</param>
/// <param name="MinimumTravelStepIntervalSeconds">Lower bound for a same-foot step interval during sustained travel.</param>
/// <param name="MaximumTravelStepIntervalSeconds">Upper bound for a same-foot step interval during sustained travel.</param>
/// <param name="MinimumSameFootStepGapSeconds"></param>
/// <param name="ExclusionWindows">Accepted crossfade-seam windows excluded from per-sample metrics.</param>
public sealed record NPCFluidityGateThresholds(
    float StanceContactOffsetMetres,
    float StanceMaximumVerticalSpeed,
    float GroundTrackWindowSeconds,
    int MinimumStanceSamples,
    int MinimumSwingSamples,
    float MaximumStanceSlipSpeed,
    float MaximumStanceSlipDistance,
    float MaximumSwingPlanarSpeed,
    float MaximumSpeedDiscontinuity,
    float TravelPhaseWarmupSeconds,
    float MinimumTravelStepIntervalSeconds,
    float MaximumTravelStepIntervalSeconds,
    float MinimumSameFootStepGapSeconds,
    IReadOnlyList<NPCFluidityExclusionWindow> ExclusionWindows)
{
    /// <summary>
    /// Initial thresholds seeded from the player gate's structure and the NPC catalogue (1.8333 s shared cycle,
    /// 0.9167 s per-foot step at rate 1), recalibrated from measured NAV-001 controls and scenario evidence in
    /// game/temp/nav001-fluidity-gate (see each parameter's citation note after calibration).
    /// </summary>
    public static NPCFluidityGateThresholds CalibratedDefaults
    {
        get;
    } = new(
        // Stance discriminators held from phase 1 (planted feet within ~0.012 m of tracked ground; toe-off
        // micro-oscillation absorbed by the min-stance merge).
        StanceContactOffsetMetres: 0.02f,
        StanceMaximumVerticalSpeed: 0.10f,
        // Half the 1.0667 s cycle always covers at least one planted foot.
        GroundTrackWindowSeconds: 0.5334f,
        MinimumStanceSamples: 3,
        MinimumSwingSamples: 10,
        // Measured accepted populations under the 1.0667 s cadence anchor (game/temp/nav001-fluidity-gate,
        // 2026-08-19): clean walk-family stance roll <=0.923 m/s; authored side-step shuffle (parked
        // NPCSideStepR control) 1.198 m/s; pure lateral-family fast playback (parked xl control, the
        // user-approved Option-A 1.62x trade-off) 1.756 m/s; interior triangle mixes of the walk and lateral
        // families (diagonal routes) up to 2.570 m/s one-tick toe-off spikes. The interior-mix territory is
        // the unified space's accepted blend-extreme cost — ESCALATED for ANIM-002 (xl/xr keyframe retiming);
        // not code-fixable containedly (spikes occur with the blend frozen and a constant rate). 2.80 m/s =
        // accepted max +9%; regression classes still fail: the phase-1 blend-drag skating and entry-restart
        // sweep rescaled to the new cadence read ~3.2-10.9 m/s.
        MaximumStanceSlipSpeed: 2.80f,
        // Coarse backstop: accepted per-interval stance travel reaches 0.386 m (diagonal routes' long stance
        // during 0.8-rate segments); the phase-1 replace-restart defect accumulated 0.52-0.59 m. 0.45 m =
        // accepted max +17%.
        MaximumStanceSlipDistance: 0.45f,
        // Measured: clean sustained walk swing ~2.4-2.5 m/s (true-world frame); the accepted entry->travel
        // crossfade seam sweeps 2.80-3.07 m/s (the 0.3 s crossfade's pose-gap cost, mirroring the player
        // gate's accepted 3.1-3.25 seam band); lateral-family swing 2.09 m/s; and the highest accepted exit
        // seam reaches 3.80 m/s across variance runs (other selected-occurrence exits measure <=3.4). 4.00 m/s = worst
        // accepted seam +5%, clean sustained +60%; the pre-fix defect classes still fail (lateral exit
        // sweeps 4.4-5.1, entry-restart 10.9). The margin over the worst accepted population is thin by
        // construction — regression discrimination leans on the stance-slip and discontinuity ceilings.
        MaximumSwingPlanarSpeed: 4.00f,
        // Measured: clean walk-family disc <=91.7 m/s^2; parked lateral-family fast playback 113.9; the
        // side-step hop seam 104.2; interior-mix toe-off spikes 152.9 (escalated territory above). 165 m/s^2
        // = accepted max +8%; the phase-1 replace-restart discontinuity (650 m/s^2) fails by 4x.
        MaximumSpeedDiscontinuity: 165f,
        // One cycle of margin past the 0.3 s entry crossfade.
        TravelPhaseWarmupSeconds: 1.2f,
        // Measured: clean same-foot step intervals are exactly 1.067 s parked (one step per foot per 1.0667 s
        // cycle); bouts span 0.800-1.45 s (rate 0.8-1.0 handoff/demand variation, detection jitter, and the
        // accepted mix territory's irregular cadence — the big-yaw arc routes sweep deep through the lateral
        // family, whose 1.62x fast playback yields one step per ~0.66 s at the pure xl point, measured 0.800 s
        // mid-arc). 0.75 s brackets the accepted lateral-mix cadence; sub-half-cycle chatter (the phase-1
        // 0.233/0.483 hitch pairs) is already merged by the same-foot onset floor, and the phase-1 hesitation
        // defect read 3.40 s.
        MinimumTravelStepIntervalSeconds: 0.75f,
        MaximumTravelStepIntervalSeconds: 1.65f,
        // Same-foot onsets closer together than this merge into one step (keep-first): one step per foot per
        // 1.0667 s shared cycle means a same-foot step cannot repeat inside half a cycle — shorter gaps are
        // contact-boundary chatter from the accepted wf/wb mix territory's low drags (+0.02-0.045 m)
        // flickering the raw stance flag without any step occurring (measured 0.233 s and 0.483 s chatter
        // pairs on the replace and diagonal cases; genuine steps measure >=0.85 s apart at rate <=1).
        MinimumSameFootStepGapSeconds: 0.55f,
        ExclusionWindows: []);
}

