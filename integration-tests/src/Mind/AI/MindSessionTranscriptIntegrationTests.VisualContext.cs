using AlleyCat.IntegrationTests.Support;
using AlleyCat.Mind.AI;
using AlleyCat.Mind.AI.Tool;
using Godot;
using Xunit;

namespace AlleyCat.IntegrationTests.Mind.AI;

/// <summary>
/// Godot-runtime coverage for the AI-011 transcript-image contracts added by AI-013 (TR-26–TR-28): a session whose
/// tools generate visual context writes each image exactly once as a sibling PNG/JPEG file beside the generating
/// turn page with relative links, and a disabled transcript toggle writes no image files anywhere.
/// </summary>
public sealed partial class MindSessionTranscriptIntegrationTests
{
    /// <summary>
    /// An enabled session whose tool generates a minimap per call writes one sibling PNG beside each generating
    /// turn page — the exact generated bytes, relatively linked at the invocation block and listed per cycle —
    /// while the invocation index carries no image links (AI-011 UR-9, TR-26–TR-27).
    /// </summary>
    [Fact]
    public async Task VisualContext_WithLoggingEnabled_WritesSiblingImagesBesideTheirTurnPages()
    {
        SceneTree sceneTree = TestUtils.GetSceneTree();
        string root = CreateTranscriptRoot();
        FixtureBag fixtures = new();
        TestAgenticMind? mind = null;
        try
        {
            MindSessionTranscriptRecorder.ResetTurnCountersForTesting();
            MindSessionTranscriptRecorder.SetRootPathOverrideForTesting(root);
            TestCharacter owner = new();
            FixturePlayerCharacter player = fixtures.Add(new FixturePlayerCharacter());
            ImageReturningTool tool = fixtures.Add(new ImageReturningTool(
            [
                [0x89, 0x50, 0x4E, 0x47],
                [0xAB, 0xCD],
            ]));
            ScriptedSessionClientProvider clientProvider = fixtures.Add(new ScriptedSessionClientProvider());
            clientProvider.EnqueueCall(ImageReturningTool.ToolNameValue);
            clientProvider.EnqueueCall(ImageReturningTool.ToolNameValue);
            clientProvider.EnqueueHoldForever();
            mind = CreateTranscriptMind(owner, player, clientProvider, tool);
            (sceneTree.CurrentScene ?? sceneTree.Root).AddChild(mind);

            await WaitUntilAsync(
                sceneTree,
                () => File.Exists(Path.Combine(GetCharacterDirectory(root), "turn-0002-minimap-1.png")));

            string characterDirectory = GetCharacterDirectory(root);
            Assert.Equal(
                [
                    "index.md",
                    "turn-0001-minimap-1.png",
                    "turn-0001.md",
                    "turn-0002-minimap-1.png",
                    "turn-0002.md",
                ],
                Directory.GetFiles(characterDirectory).Select(Path.GetFileName).Order());
            Assert.Equal(
                new byte[] { 0x89, 0x50, 0x4E, 0x47 },
                File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0001-minimap-1.png")));
            Assert.Equal(
                new byte[] { 0xAB, 0xCD },
                File.ReadAllBytes(Path.Combine(characterDirectory, "turn-0002-minimap-1.png")));
            string firstTurnPage = File.ReadAllText(Path.Combine(characterDirectory, "turn-0001.md"));
            Assert.Contains("![minimap](turn-0001-minimap-1.png)", firstTurnPage, StringComparison.Ordinal);
            Assert.Contains(
                "- **minimap:** [turn-0001-minimap-1.png](turn-0001-minimap-1.png) —",
                firstTurnPage,
                StringComparison.Ordinal);
            string secondTurnPage = File.ReadAllText(Path.Combine(characterDirectory, "turn-0002.md"));
            Assert.Contains("![minimap](turn-0002-minimap-1.png)", secondTurnPage, StringComparison.Ordinal);

            // The invocation index stays unchanged by the AI-013 amendment and carries no image links (TR-27).
            string index = File.ReadAllText(Path.Combine(characterDirectory, "index.md"));
            Assert.DoesNotContain(".png)", index, StringComparison.Ordinal);
        }
        finally
        {
            await CleanupSessionScopeAsync(sceneTree, mind, fixtures, root);
        }
    }

    /// <summary>
    /// A disabled transcript toggle writes no image files anywhere (AI-011 TR-28): the generated images exist only
    /// within the provider requests, and no transcript tree is ever created under the redirected root.
    /// </summary>
    [Fact]
    public async Task VisualContext_WithLoggingDisabled_WritesNoImageFilesAnywhere()
    {
        SceneTree sceneTree = TestUtils.GetSceneTree();
        string root = CreateTranscriptRoot();
        FixtureBag fixtures = new();
        TestAgenticMind? mind = null;
        try
        {
            MindSessionTranscriptRecorder.ResetTurnCountersForTesting();
            MindSessionTranscriptRecorder.SetRootPathOverrideForTesting(root);
            TestCharacter owner = new();
            FixturePlayerCharacter player = fixtures.Add(new FixturePlayerCharacter());
            ImageReturningTool tool = fixtures.Add(new ImageReturningTool([[1, 2, 3]]));
            ScriptedSessionClientProvider clientProvider = fixtures.Add(new ScriptedSessionClientProvider());
            clientProvider.EnqueueCall(ImageReturningTool.ToolNameValue);
            clientProvider.EnqueueHoldForever();
            mind = CreateTranscriptMind(owner, player, clientProvider, [tool], enableTranscriptLogging: false);
            (sceneTree.CurrentScene ?? sceneTree.Root).AddChild(mind);

            // The second request proves the image-carrying exchange was retained: the null-object sink ran for the
            // whole cycle while writing nothing (AI-011 TR-5/TR-28).
            await WaitUntilAsync(sceneTree, () => clientProvider.Requests.Count == 2);

            Assert.False(Directory.Exists(root), "No transcript tree may be created when logging is disabled.");
        }
        finally
        {
            await CleanupSessionScopeAsync(sceneTree, mind, fixtures, root);
        }
    }

    /// <summary>
    /// Tool whose every invocation returns an image-carrying result (AI-013 TR-5), handing out one queued payload
    /// per call so each cycle generates distinct bytes.
    /// </summary>
    private sealed partial class ImageReturningTool : AgentTool
    {
        public const string ToolNameValue = "look_around";

        private readonly Queue<byte[]> _pendingPayloads = new();

        public ImageReturningTool(params byte[][] imagePayloads)
        {
            ToolName = ToolNameValue;
            ToolDescription = "Look around.";
            foreach (byte[] payload in imagePayloads)
            {
                _pendingPayloads.Enqueue(payload);
            }
        }

        public int InvocationCount
        {
            get;
            private set;
        }

        protected override Delegate CreateDelegate() => Capture;

        private ValueTask<AgentToolResult> Capture(ScenarioContext context)
        {
            InvocationCount++;
            return ValueTask.FromResult(new AgentToolResult(
                "Map delivered.",
                image: VisualContextImage.Minimap(
                    _pendingPayloads.Dequeue(),
                    centreX: 1.5,
                    centreY: -2.5,
                    radiusMetres: 10,
                    gameTimeSeconds: 42.5)));
        }
    }
}
